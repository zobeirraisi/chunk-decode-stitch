"""Print-size figures for the manuscript.

From an nc_dump.py chunk dump (base checkpoint, stride 64) this writes:
  1. figures/qualitative_ltb_nc.pdf -- one exact match and one near miss on
     LTB's hardest bucket (same selection rule as make_paperc_qualitative.py:
     success = exact match with 4-6 crops, URLs first, then longest; near
     miss = smallest nonzero CER <= 0.18 with 3-6 crops), drawn at the text
     width with nc_failure_figure.render_examples.
  2. figures/pipeline_strip.png, figures/pipeline_crop{1..4}.png and
     figures/pipeline_data.tex -- a real exact-match example with exactly four
     crops, for the TikZ pipeline figure in main.tex (fonts then match the
     body text). Rule: shortest-read-first among exact matches whose four
     crop reads each fit in 18 characters, preferring the 36-55 bucket.

Usage (from code/):
  .venv/bin/python make_nc_figures.py --dump results/nc/dumps/base_chunks_ltb_s64.jsonl.gz
"""
import argparse
import os

from PIL import Image

from eval_ltb import levenshtein
from ltb_data import resize_aspect_preserving
from nc_common import CHUNK_W, read_jsonl, stitch_variant
from nc_failure_figure import LTB_ROOT, render_examples

FIG_DIR = "figures"


def tex_escape(s: str) -> str:
    return s.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("%", r"\%") \
            .replace("&", r"\&").replace("#", r"\#").replace("$", r"\$")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dump", default="results/nc/dumps/base_chunks_ltb_s64.jsonl.gz")
    ap.add_argument("--fig_dir", default=FIG_DIR)
    args = ap.parse_args()

    recs = read_jsonl(args.dump)
    for r in recs:
        r["pred"] = stitch_variant(r["chunks"], r["xs"], mode="full")[0]
        r["cer"] = levenshtein(r["pred"], r["gt"]) / max(len(r["gt"]), 1)

    # 1. qualitative figure
    hard = [r for r in recs if r["bucket"] == "56+"]
    succ = sorted([r for r in hard if r["pred"] == r["gt"] and 4 <= len(r["xs"]) <= 6],
                  key=lambda r: (r["gt"].startswith("http"), len(r["gt"])), reverse=True)
    fail = sorted([r for r in hard if r["pred"] != r["gt"] and 0 < r["cer"] <= 0.18
                   and 3 <= len(r["xs"]) <= 6], key=lambda r: r["cer"])
    s, f = succ[0], fail[0]
    out = os.path.join(args.fig_dir, "qualitative_ltb_nc.pdf")
    render_examples([
        (f"(a) exact match: {len(s['gt'])} characters, {len(s['xs'])} crops", s, s["pred"]),
        (f"(b) near miss: {len(f['gt'])} characters, {len(f['xs'])} crops, "
         f"CER {100 * f['cer']:.1f}%", f, f["pred"]),
    ], out, fontsize=8.0)
    print(f"wrote {out}\n  success {s['id']} {s['gt']!r}\n  near miss {f['id']} "
          f"pred={f['pred']!r} gt={f['gt']!r}")

    # 2. pipeline example
    cands = [r for r in recs if r["pred"] == r["gt"] and len(r["xs"]) == 4
             and all(len(t) <= 18 for t, _ in r["chunks"])]
    cands.sort(key=lambda r: (r["bucket"] != "36-55", -len(r["gt"])))
    p = cands[0]
    strip = resize_aspect_preserving(Image.open(os.path.join(LTB_ROOT, p["id"])).convert("RGB"))
    w = strip.size[0]
    big = lambda im: im.resize((im.size[0] * 4, im.size[1] * 4), Image.BICUBIC)
    big(strip).save(os.path.join(args.fig_dir, "pipeline_strip.png"))
    for k, x in enumerate(p["xs"], 1):
        big(strip.crop((x, 0, x + CHUNK_W, 32))).save(
            os.path.join(args.fig_dir, f"pipeline_crop{k}.png"))
    with open(os.path.join(args.fig_dir, "pipeline_data.tex"), "w") as fh:
        fh.write(f"% generated by code/make_nc_figures.py from {p['id']}\n")
        fh.write(f"\\def\\pipeW{{{w}}}\n")
        fh.write(f"\\def\\pipeXs{{{','.join(str(x) for x in p['xs'])}}}\n")
        for k, (t, _) in enumerate(p["chunks"], 1):
            fh.write(f"\\expandafter\\def\\csname pipeRead{k}\\endcsname{{{tex_escape(t)}}}\n")
        fh.write(f"\\def\\pipeOut{{{tex_escape(p['pred'])}}}\n")
    print(f"pipeline example {p['id']} w={w} xs={p['xs']} reads={[t for t, _ in p['chunks']]} "
          f"-> {p['pred']!r}")


if __name__ == "__main__":
    main()
